package io.github.alktrip.cfdi4j.tools.catalogs;

import java.time.LocalDate;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;
import java.util.Optional;
import java.util.Set;
import java.util.TreeSet;
import org.apache.poi.ss.usermodel.Sheet;
import org.apache.poi.ss.usermodel.Workbook;

/**
 * Writes the large catalogs (c_ClaveProdServ, c_ClaveUnidad and c_CodigoPostal) as tab-separated
 * resources of {@code cfdi4j-catalogs} (ADR 0003). One line per key, sorted by key, after a
 * comment line that names the source file. Values never contain tabs or line breaks: cells are
 * normalized by {@link SheetReader}.
 */
final class LargeCatalogs {

    static final String CLAVE_PROD_SERV = "c_ClaveProdServ.tsv";
    static final String CLAVE_UNIDAD = "c_ClaveUnidad.tsv";
    static final String CODIGO_POSTAL = "c_CodigoPostal.tsv";

    private final Workbook workbook;
    private final String header;

    LargeCatalogs(Workbook workbook, String sourceFile, String sha256) {
        this.workbook = workbook;
        this.header = "# Generated by tools/catalog-generator from " + sourceFile + " (SHA-256 " + sha256 + "). Do not edit.\n";
    }

    /** Generates every resource, keyed by file name. */
    Map<String, String> generate() {
        Map<String, String> files = new LinkedHashMap<>();
        files.put(CLAVE_PROD_SERV, claveProdServ());
        files.put(CLAVE_UNIDAD, claveUnidad());
        files.put(CODIGO_POSTAL, codigoPostal());
        return files;
    }

    /** clave, descripción, incluir IVA trasladado, incluir IEPS trasladado, complemento, inicio, fin. */
    String claveProdServ() {
        SheetReader r = reader("c_ClaveProdServ");
        int h = r.findRow(0, "c_ClaveProdServ");
        expect(r, h, "c_ClaveProdServ", "Descripción", "Incluir IVA trasladado", "Incluir IEPS trasladado", "Complemento que debe incluir",
                "FechaInicioVigencia", "FechaFinVigencia");
        Lines lines = new Lines(r);
        for (int row = h + 1; row <= r.lastRow(); row++) {
            String clave = r.text(row, 0);
            if (clave.isEmpty()) {
                continue;
            }
            check(r, row, 0, clave, "[0-9]{8}");
            lines.add(row, clave, r.requiredText(row, 1), r.requisito(row, 2), r.requisito(row, 3), r.text(row, 4),
                    inicio(r, row, 5), fin(r, row, 6));
        }
        return lines.text();
    }

    /** clave, nombre, inicio, fin. */
    String claveUnidad() {
        SheetReader r = reader("c_ClaveUnidad");
        int h = r.findRow(0, "c_ClaveUnidad");
        expect(r, h, "c_ClaveUnidad", "Nombre", "Descripción", "Nota", "Fecha de inicio de vigencia", "Fecha de fin de vigencia");
        Lines lines = new Lines(r);
        for (int row = h + 1; row <= r.lastRow(); row++) {
            String clave = r.text(row, 0);
            if (clave.isEmpty()) {
                continue;
            }
            check(r, row, 0, clave, "[A-Za-z0-9]{1,3}");
            lines.add(row, clave, r.requiredText(row, 1), inicio(r, row, 4), fin(r, row, 5));
        }
        return lines.text();
    }

    /** código postal, estado, inicio, fin, diferencia horaria de verano, diferencia horaria de invierno. */
    String codigoPostal() {
        Lines lines = null;
        for (String name : List.of("c_CodigoPostal_Parte_1", "c_CodigoPostal_Parte_2")) {
            SheetReader r = reader(name);
            int h = r.findRow(0, "c_CodigoPostal");
            expect(r, h, "c_CodigoPostal", "c_Estado", "c_Municipio", "c_Localidad", "Estímulo Franja Fronteriza", "Fecha inicio de vigencia",
                    "Fecha fin de vigencia", "Referencias del Huso Horario");
            r.expect(h + 1, 11, "Diferencia_Horaria_Verano");
            r.expect(h + 1, 15, "Diferencia_Horaria_Invierno");
            lines = lines == null ? new Lines(r) : lines.continueWith(r);
            for (int row = h + 2; row <= r.lastRow(); row++) {
                String cp = r.text(row, 0);
                if (cp.isEmpty()) {
                    continue;
                }
                if (cp.startsWith("Continúa en ")) {
                    break; // the SAT note that the catalog goes on in the next sheet
                }
                check(r, row, 0, cp, "[0-9]{5}");
                String estado = r.requiredText(row, 1);
                check(r, row, 1, estado, "[A-Z]{3}");
                lines.add(row, cp, estado, inicio(r, row, 5), fin(r, row, 6), offset(r, row, 11), offset(r, row, 15));
            }
        }
        return lines.text();
    }

    private SheetReader reader(String name) {
        Sheet sheet = workbook.getSheet(name);
        if (sheet == null) {
            throw new GeneratorException("sheet " + name + " not found");
        }
        return new SheetReader(sheet);
    }

    private static void expect(SheetReader r, int row, String... headers) {
        for (int c = 0; c < headers.length; c++) {
            r.expect(row, c, headers[c]);
        }
    }

    private static void check(SheetReader r, int row, int column, String value, String pattern) {
        if (!value.matches(pattern)) {
            throw r.fail(row, column, "'" + value + "' does not match " + pattern);
        }
    }

    private static String inicio(SheetReader r, int row, int column) {
        return r.date(row, column).map(LocalDate::toString).orElseThrow(() -> r.fail(row, column, "start date is required"));
    }

    private static String fin(SheetReader r, int row, int column) {
        return r.date(row, column).map(LocalDate::toString).orElse("");
    }

    /** A whole number of hours such as {@code -6}, written as {@code -06:00}. */
    private static String offset(SheetReader r, int row, int column) {
        String value = r.requiredText(row, column);
        if (!value.matches("-?[0-9]{1,2}")) {
            throw r.fail(row, column, "expected a difference in hours but found '" + value + "'");
        }
        return java.time.ZoneOffset.ofHours(Integer.parseInt(value)).getId();
    }

    /** Sorted lines with unique keys. */
    private final class Lines {
        private final Map<String, String> byKey = new java.util.TreeMap<>();
        private SheetReader reader;

        Lines(SheetReader reader) {
            this.reader = reader;
        }

        Lines continueWith(SheetReader next) {
            this.reader = next;
            return this;
        }

        void add(int row, String key, String... values) {
            String line = key + "\t" + String.join("\t", values);
            if (byKey.put(key, line) != null) {
                throw reader.fail(row, 0, "duplicated key '" + key + "'");
            }
        }

        String text() {
            StringBuilder out = new StringBuilder(header);
            byKey.values().forEach(l -> out.append(l).append('\n'));
            return out.toString();
        }
    }

    /** Keys of a generated resource, for tests. */
    static Set<String> keys(String resource) {
        Set<String> keys = new TreeSet<>();
        resource.lines().filter(l -> !l.startsWith("#")).forEach(l -> keys.add(l.substring(0, l.indexOf('\t'))));
        return keys;
    }

    static Optional<String> line(String resource, String key) {
        return resource.lines().filter(l -> l.startsWith(key + "\t")).findFirst();
    }
}
