    /** A catalog with key in column A, description in column B and the given validity columns. */
    private static KeyedCatalog simple(String sheet, String className, int inicio, int fin, List<Header> extraHeaders, List<Field> fields) {
        List<Header> headers = new ArrayList<>();
        headers.add(new Header(0, 1, "Descripción"));
        headers.add(new Header(0, inicio, VIGENCIA_INICIO));
        headers.add(new Header(0, fin, VIGENCIA_FIN));
        headers.addAll(extraHeaders);
        return new KeyedCatalog(sheet, className, 1, inicio, fin, headers, 1, fields);
    }

    private static Extractor requisito(int column) {
        return (r, row, clave, ctx) -> "Requisito." + r.requisito(row, column);
    }

    private static Extractor yesNo(int column) {
        return (r, row, clave, ctx) -> Boolean.toString(r.yesNo(row, column));
    }

    private static Extractor text(int column) {
        return (r, row, clave, ctx) -> JavaText.string(r.optionalText(row, column).orElse(null));
    }

    private static Extractor integer(int column) {
        return (r, row, clave, ctx) -> r.optionalText(row, column).map(v -> {
            if (!v.matches("[0-9]+")) {
                throw r.fail(row, column, "expected an integer but found '" + v + "'");
            }
            return v;
        }).orElse("null");
    }

    private static Extractor decimal(int column, int numericScale) {
        return (r, row, clave, ctx) -> JavaText.decimal(r.decimal(row, column, numericScale).orElse(null));
    }

    private static Extractor valorMaximo() {
        return (r, row, clave, ctx) -> {
            if (clave.equals("N")) {
                if (!r.text(row, 2).equals("NS")) {
                    throw r.fail(row, 2, "expected the NS/NdS sub-header for Nómina");
                }
                return "null";
            }
            return JavaText.decimal(r.decimal(row, 2, 0).orElseThrow(() -> r.fail(row, 2, "value is required")));
        };
    }

    private static Extractor textSet(int column) {
        return (r, row, clave, ctx) -> {
            List<String> values = split(r.text(row, column));
            return values.stream().sorted().map(JavaText::string).collect(Collectors.joining(", ", "Set.of(", ")"));
        };
    }

    private static Extractor regimenSet(int column) {
        return (r, row, clave, ctx) -> {
            List<String> values = split(r.requiredText(row, column));
            return values.stream().sorted().map(k -> ctx.constantName("c_RegimenFiscal", k))
                    .collect(Collectors.joining(", ", "Set.of(", ")"));
        };
    }

    private static List<String> split(String text) {
        return text.isEmpty()
                ? List.of()
                : Arrays.stream(text.split(",")).map(String::strip).filter(s -> !s.isEmpty()).distinct().toList();
    }

    // ---------------------------------------------------------------------------------------------
    // c_TasaOCuota: not keyed; a list of fixed values and ranges per tax and factor.
    // ---------------------------------------------------------------------------------------------

    private String tasaOCuota() {
        SheetReader r = new SheetReader(sheet("c_TasaOCuota"));
        int h = r.findRow(1, "c_TasaOCuota");
        r.expect(h, 0, "Rango o Fijo");
        r.expect(h, 3, "Impuesto");
        r.expect(h, 4, "Factor");
        r.expect(h, 5, "Traslado");
        r.expect(h, 6, "Retención");
        r.expect(h, 7, VIGENCIA_INICIO);
        r.expect(h, 8, VIGENCIA_FIN);
        r.expect(h + 1, 1, "Valor mínimo");
        r.expect(h + 1, 2, "Valor máximo");

        Map<String, String> impuestoByLabel = new LinkedHashMap<>();
        descriptions.get("c_Impuesto").forEach((clave, descripcion) -> impuestoByLabel.put(descripcion, clave));

        List<String> reglas = new ArrayList<>();
        for (int row = h + 2; row <= r.lastRow(); row++) {
            if (!r.text(row, 0).isEmpty()) {
                reglas.add(tasaOCuotaRow(r, row, impuestoByLabel));
            }
        }
        if (reglas.isEmpty()) {
            throw new GeneratorException("c_TasaOCuota: no entries");
        }
        return header
                + "package " + PACKAGE + ";\n\n"
                + "import java.math.BigDecimal;\nimport java.time.LocalDate;\nimport java.util.List;\n\n"
                + "/**\n * Catálogo {@code c_TasaOCuota}: fixed values and ranges allowed for each tax and factor.\n *\n"
                + " * <p>Generated from the official SAT catalog file (see {@link CatalogVersion}).\n */\n"
                + "public final class TasaOCuota {\n\n"
                + "    private static final List<TasaOCuotaRegla> REGLAS = List.of(\n            "
                + String.join(",\n            ", reglas) + ");\n\n"
                + "    private TasaOCuota() {}\n\n"
                + "    /**\n     * Returns every row of the catalog, in catalog order.\n     *\n     * @return the rows\n     */\n"
                + "    public static List<TasaOCuotaRegla> reglas() {\n        return REGLAS;\n    }\n}\n";
    }

    private String tasaOCuotaRow(SheetReader r, int row, Map<String, String> impuestoByLabel) {
        String tipo = r.text(row, 0);
        boolean rango = switch (tipo) {
            case "Rango" -> true;
            case "Fijo" -> false;
            default -> throw r.fail(row, 0, "expected Rango or Fijo but found '" + tipo + "'");
        };
        BigDecimal maximo = r.decimal(row, 2, 6).orElseThrow(() -> r.fail(row, 2, "value is required"));
        BigDecimal minimo = rango ? r.decimal(row, 1, 6).orElseThrow(() -> r.fail(row, 1, "value is required")) : maximo;
        if (!rango && r.decimal(row, 1, 6).isPresent()) {
            throw r.fail(row, 1, "a fixed value must not have a minimum");
        }
        String label = r.requiredText(row, 3);
        String impuestoClave = impuestoByLabel.get(IMPUESTO_ALIASES.getOrDefault(label, label));
        if (impuestoClave == null) {
            throw r.fail(row, 3, "unknown tax '" + label + "'");
        }
        String factor = r.requiredText(row, 4);
        LocalDate inicio = r.date(row, 7).orElseThrow(() -> r.fail(row, 7, "value is required"));
        LocalDate fin = r.date(row, 8).orElse(null);
        return "new TasaOCuotaRegla(" + rango + ", " + JavaText.decimal(minimo) + ", " + JavaText.decimal(maximo) + ",\n"
                + "                    " + constantName("c_Impuesto", impuestoClave) + ", " + JavaText.string(label) + ", "
                + constantName("c_TipoFactor", factor) + ", " + r.yesNo(row, 5) + ", " + r.yesNo(row, 6) + ",\n"
                + "                    " + JavaText.vigencia(inicio, fin) + ")";
    }

    private String catalogVersion() {
        return header
                + "package " + PACKAGE + ";\n\n"
                + "/** Identifies the official SAT catalog file the catalog classes were generated from. */\n"
                + "public final class CatalogVersion {\n\n"
                + "    /** File name as published by the SAT. */\n"
                + "    public static final String SOURCE_FILE = " + JavaText.string(sourceFile) + ";\n\n"
                + "    /** SHA-256 of the file, as recorded in {@code specs/SOURCES.md}. */\n"
                + "    public static final String SHA256 = " + JavaText.string(sha256) + ";\n\n"
                + "    private CatalogVersion() {}\n}\n";
    }

    // ---------------------------------------------------------------------------------------------

    /** Writes the files and removes generated files that are no longer produced. */
    static void write(Path directory, Map<String, String> files) throws IOException {
        Files.createDirectories(directory);
        try (Stream<Path> existing = Files.list(directory)) {
            for (Path file : existing.toList()) {
                String name = file.getFileName().toString();
                if (name.endsWith(".java") && !files.containsKey(name)
                        && Files.readString(file, StandardCharsets.UTF_8).startsWith(GENERATED_MARKER)) {
                    Files.delete(file);
                }
            }
        }
        for (Map.Entry<String, String> file : files.entrySet()) {
            Files.writeString(directory.resolve(file.getKey()), file.getValue(), StandardCharsets.UTF_8);
        }
        System.out.println("Generated " + files.size() + " files in " + directory + ": " + Set.copyOf(files.keySet()));
    }

    static String sha256(byte[] content) {
        try {
            return HexFormat.of().formatHex(MessageDigest.getInstance("SHA-256").digest(content));
        } catch (NoSuchAlgorithmException e) {
            throw new IllegalStateException(e);
        }
    }
